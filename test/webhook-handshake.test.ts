import { beforeEach, describe, expect, test } from "bun:test";
import { HANDSHAKE_MODES } from "../src/lib/webhook-handshake";
import { SUPPORTED_HANDSHAKE_MODES } from "../src/lib/webhook-defs";
import { serveWebhook } from "../src/lib/webhook-receive";
import {
	makeBucket,
	makeCtx,
	makeEnv,
	seedReceiver,
	type TestCtx,
	type TestEnv,
} from "./helpers/env";

// A handshake is how a provider decides whether an endpoint is real, and it is
// sent BEFORE any secret has been agreed. So the two properties every test here
// circles are: the exact bytes the provider asked for come back, and the check
// never depends on a signature -- because at handshake time there is not
// reliably one to check.
//
// Zoom's expected HMAC was computed OUTSIDE this codebase, with `openssl dgst`
// and again with python's `hmac`, both agreeing. A fixture generated by the code
// under test only ever proves the code agrees with itself.

let env: TestEnv;
let ctx: TestCtx;
let objects: Record<string, string | Uint8Array>;

beforeEach(() => {
	objects = {};
	env = makeEnv({ BUCKET: makeBucket(objects) });
	ctx = makeCtx();
});

function send(
	path: string,
	init: { method?: string; body?: BodyInit | null; headers?: Record<string, string> } = {},
) {
	const request = new Request(`https://drop.test${path}`, {
		method: init.method ?? "POST",
		headers: init.headers,
		body: init.body ?? null,
	});
	return serveWebhook(request, env, new URL(request.url), ctx);
}

/** The parsed response, typed loosely -- these assertions compare whole objects. */
async function body(res: Response): Promise<any> {
	return await res.json();
}

function rows(sql: string, ...params: unknown[]) {
	return env.DB.raw.query(sql).all(...(params as never[])) as Record<string, any>[];
}

function onlyEvent() {
	const found = rows("SELECT * FROM webhook_events");
	expect(found.length).toBe(1);
	return found[0];
}

// ---------------------------------------------------------------- meta

describe("meta -- Facebook / WhatsApp / Instagram / Threads", () => {
	const TOKEN = "verify-me-please";

	async function seedMeta(extra: Record<string, unknown> = {}) {
		await seedReceiver(env, {
			inbox: "lisa",
			slug: "fb",
			handshakeMode: "meta",
			handshakeConfig: { token: TOKEN },
			methods: "POST,GET",
			...extra,
		});
	}

	function verifyUrl(token: string, challenge = "1158201444") {
		const params = new URLSearchParams({
			"hub.mode": "subscribe",
			"hub.challenge": challenge,
			"hub.verify_token": token,
		});
		return `/h/lisa/fb?${params}`;
	}

	test("answers hub.challenge as a bare body -- not JSON, not quoted", async () => {
		await seedMeta();
		const res = await send(verifyUrl(TOKEN), { method: "GET" });

		expect(res.status).toBe(200);
		expect(await res.text()).toBe("1158201444");
		expect(res.headers.get("Content-Type")).toBe("text/plain; charset=utf-8");
	});

	test("stores the request as evidence, status='handshake'", async () => {
		await seedMeta();
		await send(verifyUrl(TOKEN), { method: "GET" });

		const event = onlyEvent();
		expect(event.status).toBe("handshake");
		expect(event.event_type).toBe("meta.url_verification");
		// Nothing was verified, and nothing claims to have been.
		expect(event.verified).toBe(null);
		expect(event.method).toBe("GET");
	});

	test("a wrong verify token is 403 -- and is still kept", async () => {
		await seedMeta();
		const res = await send(verifyUrl("not-the-token"), { method: "GET" });

		expect(res.status).toBe(403);
		// Falling through would have answered a cheerful {"ok":true} that is not the
		// challenge, and filed the probe as an ordinary event.
		expect(onlyEvent().status).toBe("handshake");
	});

	test("the verify token is redacted, the rest of the query is not", async () => {
		await seedMeta();
		await send(verifyUrl(TOKEN), { method: "GET" });

		const query = JSON.parse(onlyEvent().query);
		expect(query["hub.verify_token"]).toBe("<redacted>");
		expect(query["hub.mode"]).toBe("subscribe");
		expect(query["hub.challenge"]).toBe("1158201444");
	});

	test("an ordinary delivery to the same receiver is NOT a handshake", async () => {
		await seedMeta();
		const res = await send("/h/lisa/fb", {
			body: JSON.stringify({ object: "page", entry: [] }),
			headers: { "Content-Type": "application/json" },
		});

		expect(res.status).toBe(200);
		expect(await body(res)).toMatchObject({ ok: true });
		expect(onlyEvent().status).toBe("queued");
	});

	test("a receiver with no token configured says so rather than guessing", async () => {
		await seedReceiver(env, {
			inbox: "lisa",
			slug: "fb",
			handshakeMode: "meta",
			methods: "POST,GET",
		});
		const res = await send(verifyUrl(TOKEN), { method: "GET" });
		// 503, so Meta comes back once the operator has fixed it.
		expect(res.status).toBe(503);
	});
});

// --------------------------------------------------------------- slack

describe("slack -- url_verification", () => {
	async function seedSlack() {
		await seedReceiver(env, { inbox: "lisa", slug: "slack", handshakeMode: "slack" });
	}

	const CHALLENGE = "3eZbrw1aBm2rZgRNFdxV2595E9CY3gmdALWMmHkvFXO7tYXAYM8P";

	test("echoes the challenge back as JSON", async () => {
		await seedSlack();
		const res = await send("/h/lisa/slack", {
			body: JSON.stringify({
				token: "Jhj5dZrVaK7ZwHHjRyZWjbDl",
				challenge: CHALLENGE,
				type: "url_verification",
			}),
			headers: { "Content-Type": "application/json" },
		});

		expect(res.status).toBe(200);
		expect(await body(res)).toEqual({ challenge: CHALLENGE });
		expect(onlyEvent().status).toBe("handshake");
	});

	test("detected even when the content-type does not say JSON", async () => {
		await seedSlack();
		// The body's own `type` field is the check; a mislabelled content-type must
		// not stop a provider completing its own setup.
		const res = await send("/h/lisa/slack", {
			body: JSON.stringify({ challenge: CHALLENGE, type: "url_verification" }),
			headers: { "Content-Type": "text/plain" },
		});
		expect(await body(res)).toEqual({ challenge: CHALLENGE });
	});

	test("a real event on the same receiver goes to the queue", async () => {
		await seedSlack();
		const res = await send("/h/lisa/slack", {
			body: JSON.stringify({ type: "event_callback", event: { type: "message" } }),
			headers: { "Content-Type": "application/json" },
		});

		expect(await body(res)).toMatchObject({ ok: true });
		expect(onlyEvent().status).toBe("queued");
	});

	test("url_verification with no challenge is a 400, not a queued event", async () => {
		await seedSlack();
		const res = await send("/h/lisa/slack", {
			body: JSON.stringify({ type: "url_verification" }),
			headers: { "Content-Type": "application/json" },
		});

		expect(res.status).toBe(400);
		expect(onlyEvent().status).toBe("handshake");
	});
});

// ---------------------------------------------------------------- zoom

describe("zoom -- the CRC, against externally computed HMACs", () => {
	const SECRET = "zoomSecret123";

	// $ printf '%s' 'qgg8vlvZRS6UYooatFL8Aw' \
	//     | openssl dgst -sha256 -hmac 'zoomSecret123' -hex
	// Confirmed a second time with python hmac.new(...).hexdigest().
	const PLAIN = "qgg8vlvZRS6UYooatFL8Aw";
	const ENCRYPTED = "3ee215dfbe53223d6ab24ea678f99d586ea8dc959ce3f737482a1a702f29ac2f";

	// A plainToken whose digest begins with a zero nibble, so a hex encoder that
	// dropped leading zeros would come out 63 characters and fail here.
	const PLAIN_LEADING_ZERO = "tok-5";
	const ENCRYPTED_LEADING_ZERO = "07c38efe9a2a0bbfa23d0c504bd0e43886e772f2bf3fadd3df011f14d035d4d0";

	function crc(plainToken: string) {
		return JSON.stringify({
			payload: { plainToken },
			event_ts: 1654503849680,
			event: "endpoint.url_validation",
		});
	}

	async function seedZoom(extra: Record<string, unknown> = {}) {
		await seedReceiver(env, {
			inbox: "lisa",
			slug: "zoom",
			handshakeMode: "zoom",
			handshakeConfig: { secret: SECRET },
			...extra,
		});
	}

	test("answers {plainToken, encryptedToken} with the HMAC openssl computed", async () => {
		await seedZoom();
		const res = await send("/h/lisa/zoom", {
			body: crc(PLAIN),
			headers: { "Content-Type": "application/json" },
		});

		expect(res.status).toBe(200);
		expect(await body(res)).toEqual({ plainToken: PLAIN, encryptedToken: ENCRYPTED });
	});

	test("a digest with a leading zero keeps all 64 characters", async () => {
		await seedZoom();
		const res = await send("/h/lisa/zoom", {
			body: crc(PLAIN_LEADING_ZERO),
			headers: { "Content-Type": "application/json" },
		});

		const answer = (await body(res)) as { encryptedToken: string };
		expect(answer.encryptedToken).toBe(ENCRYPTED_LEADING_ZERO);
		expect(answer.encryptedToken.length).toBe(64);
	});

	test("stored as a handshake, with the event name Zoom used", async () => {
		await seedZoom();
		await send("/h/lisa/zoom", {
			body: crc(PLAIN),
			headers: { "Content-Type": "application/json" },
		});

		const event = onlyEvent();
		expect(event.status).toBe("handshake");
		expect(event.event_type).toBe("endpoint.url_validation");
	});

	test("the 72-hour re-validation is its own row, never a duplicate", async () => {
		// Byte-identical to the first request, on a receiver that dedupes by body
		// hash. A handshake must never answer "duplicate" -- Zoom is asking again
		// and expects the hash again.
		await seedZoom({ extract: { dedupe: "body-hash" } });
		await send("/h/lisa/zoom", {
			body: crc(PLAIN),
			headers: { "Content-Type": "application/json" },
		});
		const res = await send("/h/lisa/zoom", {
			body: crc(PLAIN),
			headers: { "Content-Type": "application/json" },
		});

		expect(await body(res)).toEqual({ plainToken: PLAIN, encryptedToken: ENCRYPTED });
		expect(rows("SELECT * FROM webhook_events").length).toBe(2);
	});

	test("no secret configured is 503 -- ours to fix, so Zoom should retry", async () => {
		await seedReceiver(env, { inbox: "lisa", slug: "zoom", handshakeMode: "zoom" });
		const res = await send("/h/lisa/zoom", {
			body: crc(PLAIN),
			headers: { "Content-Type": "application/json" },
		});
		expect(res.status).toBe(503);
	});

	test("a CRC with no plainToken is a 400", async () => {
		await seedZoom();
		const res = await send("/h/lisa/zoom", {
			body: JSON.stringify({ event: "endpoint.url_validation", payload: {} }),
			headers: { "Content-Type": "application/json" },
		});
		expect(res.status).toBe(400);
	});
});

// ------------------------------------------- the ordering guarantee

describe("the handshake NEVER reaches the verifier", () => {
	const SECRET = "zoomSecret123";
	const PLAIN = "qgg8vlvZRS6UYooatFL8Aw";
	const ENCRYPTED = "3ee215dfbe53223d6ab24ea678f99d586ea8dc959ce3f737482a1a702f29ac2f";

	const crc = JSON.stringify({
		payload: { plainToken: PLAIN },
		event_ts: 1654503849680,
		event: "endpoint.url_validation",
	});

	// A receiver that verifies deliveries AND does a handshake -- which is the
	// normal Zoom setup, since the CRC arrives while you are still configuring the
	// very secret that would sign it.
	async function seedBoth() {
		await seedReceiver(env, {
			inbox: "lisa",
			slug: "zoom",
			authMode: "digest",
			authConfig: { secret: "signing-key", header: "sign" },
			handshakeMode: "zoom",
			handshakeConfig: { secret: SECRET },
		});
	}

	test("a handshake with a deliberately invalid signature still succeeds", async () => {
		await seedBoth();
		const res = await send("/h/lisa/zoom", {
			body: crc,
			headers: { "Content-Type": "application/json", sign: "deadbeef".repeat(8) },
		});

		expect(res.status).toBe(200);
		expect(await body(res)).toEqual({ plainToken: PLAIN, encryptedToken: ENCRYPTED });

		const event = onlyEvent();
		expect(event.status).toBe("handshake");
		// null, not 0. A 0 would mean the verifier ran and said no; null means it
		// was never asked, which is the whole point of the ordering.
		expect(event.verified).toBe(null);
	});

	test("the SAME receiver rejects that signature on an ordinary delivery", async () => {
		// The control. Without this, the test above would also pass on a receiver
		// whose verification was simply broken.
		await seedBoth();
		const res = await send("/h/lisa/zoom", {
			body: JSON.stringify({ event: "meeting.started" }),
			headers: { "Content-Type": "application/json", sign: "deadbeef".repeat(8) },
		});

		expect(res.status).toBe(401);
		expect(onlyEvent().verified).toBe(0);
	});
});

// ---------------------------------------------------------------- echo

describe("echo -- short, non-JSON bodies come straight back", () => {
	async function seedEcho(config: Record<string, unknown> = {}) {
		await seedReceiver(env, {
			inbox: "lisa",
			slug: "echo",
			handshakeMode: "echo",
			handshakeConfig: config,
		});
	}

	test("returns the raw body verbatim", async () => {
		await seedEcho();
		const res = await send("/h/lisa/echo", { body: "challenge-abc123" });

		expect(res.status).toBe(200);
		expect(await res.text()).toBe("challenge-abc123");
		expect(onlyEvent().status).toBe("handshake");
	});

	test("byte-identical for a body that is not valid UTF-8", async () => {
		await seedEcho();
		const raw = new Uint8Array([0x00, 0xff, 0xc3, 0x28, 0x89, 0x50, 0x4e, 0x47]);
		const res = await send("/h/lisa/echo", { body: raw });

		expect(new Uint8Array(await res.arrayBuffer())).toEqual(raw);
	});

	test("a JSON object is a real event, not a challenge", async () => {
		await seedEcho();
		const res = await send("/h/lisa/echo", {
			body: JSON.stringify({ hello: "world" }),
			headers: { "Content-Type": "application/json" },
		});

		expect(await body(res)).toMatchObject({ ok: true });
		expect(onlyEvent().status).toBe("queued");
	});

	test("a bare number is echoed -- valid JSON, but not a payload", async () => {
		await seedEcho();
		const res = await send("/h/lisa/echo", { body: "1158201444" });
		expect(await res.text()).toBe("1158201444");
	});

	test("anything over the limit is a delivery", async () => {
		await seedEcho({ maxBytes: 8 });
		const res = await send("/h/lisa/echo", { body: "far too long to be a challenge" });

		expect(await body(res)).toMatchObject({ ok: true });
		expect(onlyEvent().status).toBe("queued");
	});

	test("an empty body is not a challenge either", async () => {
		await seedEcho();
		const res = await send("/h/lisa/echo", { body: "" });
		expect(await body(res)).toMatchObject({ ok: true });
	});
});

// -------------------------------------------------------------- static

describe("static -- a fixed answer to a configured shape", () => {
	test("answers the configured status and body on a match", async () => {
		await seedReceiver(env, {
			inbox: "lisa",
			slug: "odd",
			handshakeMode: "static",
			handshakeConfig: {
				when: { method: "GET", subpath: "setup" },
				status: 204,
				body: "",
			},
			methods: "POST,GET",
		});

		const res = await send("/h/lisa/odd/setup", { method: "GET" });
		expect(res.status).toBe(204);
		expect(onlyEvent().status).toBe("handshake");
	});

	test("every condition must hold -- one miss and it is a delivery", async () => {
		await seedReceiver(env, {
			inbox: "lisa",
			slug: "odd",
			handshakeMode: "static",
			handshakeConfig: { when: { method: "GET", subpath: "setup" }, body: "ok" },
			methods: "POST,GET",
		});

		const res = await send("/h/lisa/odd/elsewhere", { method: "GET" });
		expect(await body(res)).toMatchObject({ ok: true });
		expect(onlyEvent().status).toBe("queued");
	});

	test("an empty predicate matches NOTHING, so it cannot swallow the queue", async () => {
		await seedReceiver(env, {
			inbox: "lisa",
			slug: "odd",
			handshakeMode: "static",
			handshakeConfig: { when: {}, body: "swallowed" },
		});

		const res = await send("/h/lisa/odd", { body: "an ordinary delivery" });
		expect(await body(res)).toMatchObject({ ok: true });
		expect(onlyEvent().status).toBe("queued");
	});

	test("a header the predicate matches on is a shared secret, and is redacted", async () => {
		await seedReceiver(env, {
			inbox: "lisa",
			slug: "odd",
			handshakeMode: "static",
			handshakeConfig: { when: { header: { "x-setup-token": "s3cr3t" } }, body: "ok" },
		});

		const res = await send("/h/lisa/odd", {
			body: "ping",
			headers: { "X-Setup-Token": "s3cr3t", "X-Trace": "keep-me" },
		});

		expect(await res.text()).toBe("ok");
		const headers = JSON.parse(onlyEvent().headers);
		expect(headers["x-setup-token"]).toBe("<redacted>");
		expect(headers["x-trace"]).toBe("keep-me");
	});
});

// ------------------------------------------------------- shared rules

describe("what a handshake is not", () => {
	test("the receiver's configured response_body does not override the challenge", async () => {
		// The provider dictates the answer. A receiver that overrode it would fail
		// its own setup while looking perfectly configured.
		await seedReceiver(env, {
			inbox: "lisa",
			slug: "slack",
			handshakeMode: "slack",
			responseBody: "thanks!",
			responseContentType: "text/plain",
		});

		const res = await send("/h/lisa/slack", {
			body: JSON.stringify({ challenge: "abc", type: "url_verification" }),
			headers: { "Content-Type": "application/json" },
		});
		expect(await body(res)).toEqual({ challenge: "abc" });
	});

	test("a handshake does not count as an event", async () => {
		const id = await seedReceiver(env, {
			inbox: "lisa",
			slug: "echo",
			handshakeMode: "echo",
		});
		await send("/h/lisa/echo", { body: "challenge" });
		await ctx.settle();

		const receiver = rows("SELECT event_count FROM webhook_receivers WHERE id = ?", id)[0];
		// The counter describes the queue, and a handshake never joins it.
		expect(receiver.event_count).toBe(0);
	});

	test("handshake_mode 'none' means every request is a delivery", async () => {
		await seedReceiver(env, { inbox: "lisa", slug: "plain" });
		const res = await send("/h/lisa/plain", {
			body: JSON.stringify({ type: "url_verification", challenge: "abc" }),
			headers: { "Content-Type": "application/json" },
		});

		expect(await body(res)).toMatchObject({ ok: true });
		expect(onlyEvent().status).toBe("queued");
	});
});

describe("the supported-mode list is derived, not typed", () => {
	test("every implemented mode is registerable, and nothing else is", () => {
		// The two halves of a fail-closed gate cannot drift if only one of them
		// exists. A mode in the list but not the table would register and then never
		// answer; one in the table but not the list would be unreachable.
		expect(SUPPORTED_HANDSHAKE_MODES).toEqual(["none", ...HANDSHAKE_MODES]);
		expect(HANDSHAKE_MODES).toEqual(["meta", "slack", "zoom", "echo", "static"]);
	});
});
